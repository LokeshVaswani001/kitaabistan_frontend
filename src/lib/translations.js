// 16 more interface languages (Arabic → Japanese), fully offline: the core
// labels from ui.js plus the complete dictionary from locales/lang, so every
// key English has, these have too. Anything still missing falls back below.
for (const code of new Set([...Object.keys(UI_LOCALES), ...Object.keys(LANG_LOCALES)])) {
  translations[code] = {
    ...(translations[code] || {}),
    ...(UI_LOCALES[code] || {}),
    ...(LANG_LOCALES[code] || {}),
  };
}

export function t(lang, key, vars = {}) {
  const dict = translations[lang] || translations.en;
  let str = dict[key] ?? translations.en[key] ?? key;
  Object.entries(vars).forEach(([k, v]) => {
    str = str.replace(`{${k}}`, v);
  });
  return str;
}
